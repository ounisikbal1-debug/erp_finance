const InterfaceLanguageContext = createContext<InterfaceLanguage>('FR');

export function InterfaceLanguageProvider({
  language,
  children,
}: {
  language: InterfaceLanguage;
  children: ReactNode;
}) {
  return createElement(InterfaceLanguageContext.Provider, { value: language }, children);
}

export function useInterfaceLanguage(): InterfaceLanguage {
  return useContext(InterfaceLanguageContext);
}

export function isRightToLeft(language: InterfaceLanguage): boolean {
  return language === 'AR';
}

export function applyInterfaceLanguageToDocument(
  target: { documentElement: { lang: string; dir: string } },
  language: InterfaceLanguage,
): void {
  target.documentElement.lang = getHtmlLanguage(language);
  target.documentElement.dir = isRightToLeft(language) ? 'rtl' : 'ltr';
}

export function getHtmlLanguage(language: InterfaceLanguage): string {
  return language === 'AR' ? 'ar-TN' : language === 'EN' ? 'en' : 'fr-TN';
}

